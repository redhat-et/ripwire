#!/usr/bin/env bash
# docdemotefpcheck.sh — gate for the PROSE condition on --recall's size+fences generated-doc arm, and for
# the header naming the docs it demoted (DOCS-DEMOTE-FP, 2026-11-02).
#
# The defect. src/docparse.h classifyGeneratedDoc demoted any doc >= 5x the corpus median with >= 35 % of
# its lines inside ``` fences. A hand-written reference page full of short examples clears both, and in a
# corpus of many tiny docs 5x the median is only a few KB, so the best reference pages of other repos ranked
# below every other match: even the page's own heading as the query missed it. The arm now also requires
# that the doc's own PROSE (non-blank, non-heading lines outside every fence) be under 15 % of its bytes.
# A capture or test golden has almost none; a reference page has 30 % or more (measured, see docparse.h).
# Separately, the header said generated_demoted=N but never which docs; it now names up to 5 of them.
#
# RED (binary before the change, 5d6438d7):
#   #1 doc for the reference page's own heading = a small doc, ref_server.md demoted to the bottom
#   ref_server.md and near_prose_above.md carry [generated_demoted: size+fences]
#   the header names no demoted path
# GREEN: the reference page is #1 for its heading with lines= covering it and no demotion note; the truly
#   generated shapes (fence dump with a caption per block, a heading per block, the marker arm) and every
#   near miss on the far side of a threshold stay demoted; every near miss on the near side does not; the
#   header names the demoted docs best-first with the cap and the encoding the help text states.
#
# Usage: bash test/docdemotefpcheck.sh [BIN]   (BIN = $1, else $RIPWIRE_BIN, else build/ripwire)
set -u
ROOT="$( cd "$( dirname "$0" )/.." && pwd )"
BIN="${1:-${RIPWIRE_BIN:-$ROOT/build/ripwire}}"
[ "${BIN#/}" = "$BIN" ] && BIN="$ROOT/$BIN"
echo "docdemotefpcheck: BIN=$BIN"
[ -x "$BIN" ] || { echo "no ripwire binary at $BIN — build first"; exit 2; }
fail=0
ok(){ printf '  PASS  %s\n' "$*" || { fail=1; printf '  FAIL  could not write the PASS line for: %s\n' "$*"; }; return 0; }
no(){ printf '  FAIL  %s\n' "$*"; fail=1; }

TMP="$( mktemp -d )"; trap 'rm -rf "$TMP"' EXIT
R="$TMP/repo"; mkdir -p "$R"

# ── fixture helpers: fixed-width lines, so each doc's fence fraction and prose share are known exactly ──
L69='abcdefghij abcdefghij abcdefghij abcdefghij abcdefghij abcdefghij zzz'   # 69 bytes
[ "${#L69}" -eq 69 ] || { echo "fixture line is ${#L69} bytes, expected 69"; exit 2; }
prose(){ local i=0; while [ "$i" -lt "$1" ]; do printf '%s\n' "$L69"; i=$(( i + 1 )); done; }
fence(){ printf '```\n'; local i=0; while [ "$i" -lt "$1" ]; do printf '%s\n' "$L69"; i=$(( i + 1 )); done; printf '```\n'; }
blank(){ local i=0; while [ "$i" -lt "$1" ]; do printf '\n'; i=$(( i + 1 )); done; }
# blocks NAME COUNT PROSE CODE BLANK [HEADED]: COUNT blocks of (PROSE prose lines, a fence of CODE lines,
# BLANK blank lines); HEADED=1 opens each block with an ATX heading, which is structure, never prose.
blocks(){
    local name=$1 n=$2 p=$3 c=$4 b=$5 headed=${6:-0} i=0
    { printf '# %s zqcommon\n' "$name"
      while [ "$i" -lt "$n" ]; do
          [ "$headed" = 1 ] && printf '## %s\n' "$L69"
          prose "$p"; fence "$c"; blank "$b"; i=$(( i + 1 ))
      done; } > "$R/$name.md"
}

# 40 small hand-written docs of exactly 1000 bytes: the corpus median is 1000, the size line 5000 B. Each
# mentions "server option" so a small doc outranks a DEMOTED reference page on that page's own heading.
k=0; while [ "$k" -lt 40 ]; do
    { printf '# small %-11s\n' "$( printf '%04d' "$k" )"
      printf '%-68s\n' "zqcommon server option note $k"
      prose 13; } > "$R/small_$k.md"
    k=$(( k + 1 ))
done

# 1) the hand-written reference page (fastify Server.md shape): per option a heading, three prose lines
#    explaining it, an example fence of six lines. Fenced lines 8/15 = 0.53, prose share ~0.43, ~19 KB.
{ printf '# Server reference zqcommon\n\n'
  k=0; while [ "$k" -lt 40 ]; do
      if [ "$k" -eq 17 ]; then printf '## Server option zqbodylimit\n\n'; else printf '## Server option opt%02d\n\n' "$k"; fi
      prose 3; blank 1; fence 6; blank 1; k=$(( k + 1 ))
  done; } > "$R/ref_server.md"

# 2) generated: a fence dump with a one-line caption per block (a command capture). prose 69/639 = 0.11.
blocks dump_caption 30 1 7 1
# 3) generated: a long heading per block over a short fence and no prose at all (a test golden whose
#    headings name output files). Headings are a quarter of its bytes, so counting them as prose would
#    lift it over 0.15: the heading exclusion is load-bearing here.
blocks dump_headed 40 0 3 1 1
# 4) marker arm: small, prose-shaped, and says it is generated.
{ printf '# API dump zqcommon\n<!-- @generated by apidump — DO NOT EDIT -->\n'; prose 10; } > "$R/apidump_marker.md"
# 5) near misses on the PROSE threshold (0.15): one caption line per block, the fence length sets the share.
blocks near_prose_above 40 1 5 1     # 69/429 = 0.161 -> NOT demoted
blocks near_prose_below 40 1 6 1     # 69/499 = 0.138 -> demoted
# 6) near misses on the FENCE threshold (0.35), no prose, blank lines set the fraction.
blocks near_fence_below 60 0 3 10    # 5/15 = 0.333 -> NOT demoted
blocks near_fence_above 60 0 3 9     # 5/14 = 0.357 -> demoted
# 7) near misses on the SIZE line (5 x 1000 B): the dump_headed shape at ~4.6 KB and ~5.4 KB (over the
#    4096 B floor in both, so only the ratio decides).
blocks near_size_below 9 0 7 1      # ~4.5 KB
blocks near_size_above 11 0 7 1     # ~5.4 KB

# premise: measure each fixture with the rule's own definitions (awk replica) and print it, so a fixture
# that drifts across a threshold fails here instead of passing for the wrong reason.
# The fence rule is CommonMark's closer: an opener is 3+ backticks (no backtick after the run) or 3+ tildes;
# only the same character, a run at least as long and nothing but whitespace after it closes the fence.
measure(){ awk '
    { n++; s=$0; sub(/^[ \t]+/, "", s); c=substr(s,1,1); run=0
      if (c=="`" || c=="~") { t=s; while (substr(t,1,1)==c) { run++; t=substr(t,2) } }
      if (inside) { fz++; if (c==oc && run>=orun && t ~ /^[ \t\r]*$/) inside=0; next }
      if (run>=3 && !(c=="`" && index(t,"`"))) { inside=1; oc=c; orun=run; fz++; next }
      if (s=="" || s=="\r") next
      if (match(s, /^#{1,6}([ \t]|$)/)) next
      pb += length($0) }
    END { printf "%d %.3f %.3f\n", bytes, (n?fz/n:0), pb/bytes }' bytes="$( wc -c < "$1" | tr -d ' ' )" "$1"; }
premise(){   # premise FILE  BYTES-cmp  FENCE-cmp  PROSE-cmp  (each "lt X" / "ge X")
    local m; m="$( measure "$R/$1" )"; set -- "$1" "$2" "$3" "$4" $m
    awk -v f="$1" -v sc="$2" -v fc="$3" -v pc="$4" -v b="$5" -v ff="$6" -v ps="$7" 'function chk(c,v){split(c,a," "); return (a[1]=="lt") ? v<a[2] : v>=a[2]}
        BEGIN{ okk = chk(sc,b) && chk(fc,ff) && chk(pc,ps); printf "  %-5s premise %s bytes=%d fenced=%.3f prose=%.3f\n", okk?"ok":"BAD", f, b, ff, ps; exit !okk }' \
        || no "premise for $1 does not hold — the fixture no longer tests its threshold"
}
premise ref_server.md        "ge 5000" "ge 0.35" "ge 0.30"
premise dump_caption.md      "ge 5000" "ge 0.35" "lt 0.15"
premise dump_headed.md       "ge 5000" "ge 0.35" "lt 0.01"
premise near_prose_above.md  "ge 5000" "ge 0.35" "ge 0.15"
premise near_prose_below.md  "ge 5000" "ge 0.35" "lt 0.15"
premise near_fence_below.md  "ge 5000" "lt 0.35" "lt 0.15"
premise near_fence_above.md  "ge 5000" "ge 0.35" "lt 0.15"
premise near_size_below.md   "lt 5000" "ge 0.35" "lt 0.15"
premise near_size_above.md   "ge 5000" "ge 0.35" "lt 0.15"
premise near_size_below.md   "ge 4096" "ge 0.35" "lt 0.15"

# ── runs ─────────────────────────────────────────────────────────────────────────────────────────────
# run() is called inside $( … ), a subshell: a failure is recorded in a FILE, read at the end, since a
# variable or a FAIL line printed there would be lost or captured as the answer.
run(){ local out rc; out="$( perl -e 'alarm 60; exec @ARGV' "$BIN" "$R" --no-cache "$@" 2>"$TMP/err" )"; rc=$?
       [ "$rc" -eq 0 ] || printf 'rc=%s for %s: %s\n' "$rc" "$*" "$( head -c 300 "$TMP/err" )" >> "$TMP/rcfail"
       printf '%s' "$out"; }
hdr(){ printf '%s\n' "${1%%$'\n'*}"; }
note_for(){ printf '%s\n' "$1" | grep -F '━━' | grep -F " $2 " | grep -oE '\[generated_demoted: [a-z+]+\]'; }
seen(){ printf '%s\n' "$1" | grep -F '━━' | grep -qF " $2 "; }

ALL="$( run --recall=zqcommon --top-k=100 --max-tokens=400000 )"
[ -n "$ALL" ] && [ "$( printf '%s\n' "$ALL" | grep -cF '━━' )" -ge 50 ] \
    && ok "the all-docs probe printed $( printf '%s\n' "$ALL" | grep -cF '━━' ) separator lines" \
    || no "the all-docs probe printed no rows (rc or crash): $( hdr "$ALL" | head -c 200 )"

# 1) verdict per doc — a positive twin for every negative: the note is read off a row that IS printed.
expect(){   # expect FILE NOTE  (NOTE "" = must be printed and carry no demotion note)
    local f=$1 want=$2 got
    seen "$ALL" "$f" || { no "$f is not printed at all — cannot read its verdict"; return; }
    got="$( note_for "$ALL" "$f" )"
    if [ "$got" = "$want" ]; then ok "$f: ${want:-not demoted}"; else no "$f: expected '${want:-no note}', got '${got:-no note}'"; fi
}
expect ref_server.md        ""
expect near_prose_above.md  ""
expect near_fence_below.md  ""
expect near_size_below.md   ""
expect small_0.md           ""
expect dump_caption.md      "[generated_demoted: size+fences]"
expect dump_headed.md       "[generated_demoted: size+fences]"
expect near_prose_below.md  "[generated_demoted: size+fences]"
expect near_fence_above.md  "[generated_demoted: size+fences]"
expect near_size_above.md   "[generated_demoted: size+fences]"
expect apidump_marker.md    "[generated_demoted: marker]"

# 2) the exact heading as the query serves the reference page first, with its section's lines.
HEAD_Q="$( run --recall="Server option zqbodylimit" )"
top="$( printf '%s\n' "$HEAD_Q" | grep -F '━━' | head -1 )"
want_line="$( grep -n '^## Server option zqbodylimit$' "$R/ref_server.md" | cut -d: -f1 )"
lines_attr="$( printf '%s' "$top" | grep -oE 'lines="[0-9,-]+"' | head -1 )"
covered=0
for span in $( printf '%s' "$lines_attr" | tr -d 'lines="' | tr ',' ' ' ); do
    lo=${span%-*}; hi=${span#*-}
    [ -n "$want_line" ] && [ "$lo" -le "$want_line" ] && [ "$want_line" -le "$hi" ] && covered=1
done
{ grep -qF ' ref_server.md ' <<<"$top" && [ "$covered" = 1 ]; } \
    && ok "heading query serves ref_server.md first, $lines_attr covers line $want_line (RED: a small doc first)" \
    || no "heading query: first row '$( printf '%s' "$top" | head -c 160 )', lines=$lines_attr, heading at line $want_line"
grep -q '^## Server option zqbodylimit$' <<<"$HEAD_Q" \
    && ok "the served body holds the heading line itself" || no "the served body lacks the heading line"

# 3) the header names the demoted docs: 6 demoted, 5 named best-first, generated_demoted_named=5.
H="$( hdr "$ALL" )"
paths="$( printf '%s' "$H" | sed -n 's/.* generated_demoted_paths="\([^"]*\)".*/\1/p' )"
order="$( printf '%s\n' "$ALL" | grep -F '━━' | grep -F 'generated_demoted:' | head -5 | sed -E 's/^━━ ([^ ]+) .*/\1/' | paste -sd, - )"
grep -q ' generated_demoted=6 generated_demoted_named=5 generated_demoted_paths="' <<<"$H" \
    && ok "header: generated_demoted=6 generated_demoted_named=5 generated_demoted_paths=…" \
    || no "header lacks the 6/5 demoted naming: $( printf '%s' "$H" | head -c 400 )"
[ -n "$paths" ] && [ "$paths" = "$order" ] \
    && ok "named paths = the first 5 demoted separator rows, best-first ($paths)" \
    || no "named paths '$paths' differ from the demoted rows in rank order '$order'"

# 4) the names survive the --top-k cut, where no demoted separator is printed at all.
TOP2="$( run --recall=zqcommon --top-k=2 )"
{ [ -n "$paths" ] && [ "$( printf '%s\n' "$TOP2" | grep -cF 'generated_demoted:' )" = 0 ] \
  && [ "$( printf '%s' "$( hdr "$TOP2" )" | sed -n 's/.* generated_demoted_paths="\([^"]*\)".*/\1/p' )" = "$paths" ]; } \
    && ok "--top-k=2: no demoted row printed, the header still names the same 5" \
    || no "--top-k=2 header: $( hdr "$TOP2" | head -c 400 )"

# 5) a query no demoted doc matches says nothing about demotion (silence = it did not happen).
NONE="$( run --recall=zqbodylimit )"
{ grep -qF ' ref_server.md ' <<<"$NONE" && ! grep -q 'generated_demoted' <<<"$( hdr "$NONE" )"; } \
    && ok "a query matching no demoted doc carries no generated_demoted attribute" \
    || no "no-demotion query header: $( hdr "$NONE" | head -c 300 )"

# 6) encoding: a demoted path holding '"', ',' and '%' is percent-encoded; one name, so no _named=.
R2="$TMP/enc"; mkdir -p "$R2"
k=0; while [ "$k" -lt 4 ]; do printf '# note %d\nzqenc plain note %d\n' "$k" "$k" > "$R2/n$k.md"; k=$(( k + 1 )); done
printf '# odd\n<!-- @generated by x -->\nzqenc odd\n' > "$R2/we\"ird,%n.md"
ENC="$( perl -e 'alarm 60; exec @ARGV' "$BIN" "$R2" --no-cache --recall=zqenc 2>/dev/null )"; erc=$?
{ [ "$erc" -eq 0 ] && hdr "$ENC" | grep -qF ' generated_demoted=1 generated_demoted_paths="we%22ird%2C%25n.md"' \
  && ! hdr "$ENC" | grep -q 'generated_demoted_named'; } \
    && ok "odd path percent-encoded in generated_demoted_paths, no _named= when all are named" \
    || no "encoding (rc=$erc): $( hdr "$ENC" | head -c 300 )"

# 7) MCP memory_recall carries the same header (one front door, recallFor).
MCPH="$( python3 - "$BIN" "$R" <<'PY'
import json, subprocess, sys
msgs = [ { "jsonrpc": "2.0", "id": 1, "method": "initialize" },
         { "jsonrpc": "2.0", "id": 2, "method": "tools/call",
           "params": { "name": "memory_recall", "arguments": { "path": sys.argv[2], "task": "zqcommon", "top_k": 2 } } } ]
p = subprocess.run( [ sys.argv[1], "--mcp" ], input = "\n".join( json.dumps( m ) for m in msgs ) + "\n",
                    capture_output = True, text = True, timeout = 120 )
for line in p.stdout.splitlines():
    try: d = json.loads( line )
    except ValueError: continue
    if d.get( "id" ) == 2 and "result" in d:
        print( d[ "result" ][ "content" ][ 0 ][ "text" ].split( "\n", 1 )[ 0 ] )
PY
)"
grep -qF " generated_demoted_paths=\"$paths\"" <<<"$MCPH" \
    && ok "MCP memory_recall header names the same 5" || no "MCP header: $( printf '%s' "$MCPH" | head -c 300 )"

# 9) CommonMark fences (fix round 1, CodeRabbit's docparse.h thread). The scanner used to TOGGLE on any
#    line starting with ```, so a ````-fence quoting a ```bash block "closed" at the inner line and the rest
#    of the dump counted as prose: this repo's own captures (a ````` fence holding a ```bash block cut by
#    "… [N more lines]") measured prose 0.82 and escaped. A separate corpus, so arms 1-8 keep their counts.
#    RED on 66683e5f: nest_dump, trunc_capture, info_closer_dump, tilde_dump undemoted.
R3="$TMP/fence"; mkdir -p "$R3"
python3 - "$R3" <<'PY' || no "fence fixture generator failed"
import sys, os
R = sys.argv[1]
L = "abcdefghij abcdefghij abcdefghij abcdefghij abcdefghij abcdefghij zzz"   # 69 bytes
def w(name, text, nl="\n"):
    open(os.path.join(R, name), "w", newline="").write(text.replace("\n", nl))
for k in range(40):
    w(f"small_{k}.md", f"# small {k:04d}\n" + f"zqfence server option note {k}".ljust(68) + "\n" + (L + "\n") * 13)
def dump(n, inner):   # a capture: one caption line per quoted block
    return "# capture zqfence\n" + "".join(f"{L}\n" + inner + "\n" for _ in range(n))
w("nest_dump.md",        dump(30, "````markdown\n" + f"{L}\n{L}\n```rust\n" + f"{L}\n" * 4 + f"```\n{L}\n````\n"))
w("trunc_capture.md",    dump(30, "`````\n" + f"{L}\n```bash\n" + f"{L}\n" * 5 + "… [130 more lines]\n`````\n"))
w("info_closer_dump.md", dump(30, "````\n" + f"{L}\n" * 3 + "````bash\n" + f"{L}\n" * 3 + "````\n"))   # an info string never closes
w("tilde_dump.md",       dump(30, "~~~\n" + f"{L}\n```\n" + f"{L}\n" * 4 + f"```\n{L}\n~~~\n"))
w("indented_dump.md",    dump(30, "   ```\n" + f"   {L}\n" * 7 + "   ```\n"))                       # closer indented 3
w("handwritten_quote.md", "# Writing docs zqfence\n\n" + "".join(f"## Example {k}\n\n" + f"{L}\n" * 3
                          + "\n````markdown\n" + f"{L}\n```js\n" + f"{L}\n" * 3 + "```\n````\n\n" for k in range(30)))
w("crlf_ref.md", "# CRLF reference zqfence\n\n" + "".join(f"## Option {k}\n\n" + f"{L}\n" * 3 + "\n```\n" + f"{L}\n" * 6
                 + "```\n\n" for k in range(30)), "\r\n")
w("crlf_caption.md", dump(30, "```\n" + f"{L}\n" * 7 + "```"), "\r\n")
w("crlf_headed.md", "# crlf headed zqfence\n" + "".join(f"## {L}\n```\n" + f"{L}\n" * 3 + "```\n\n" for _ in range(40)), "\r\n")
PY
R_SAVE=$R; R=$R3
premise nest_dump.md         "ge 5000" "ge 0.35" "lt 0.15"
premise trunc_capture.md     "ge 5000" "ge 0.35" "lt 0.15"
premise info_closer_dump.md  "ge 5000" "ge 0.35" "lt 0.15"
premise tilde_dump.md        "ge 5000" "ge 0.35" "lt 0.15"
premise indented_dump.md     "ge 5000" "ge 0.35" "lt 0.15"
premise handwritten_quote.md "ge 5000" "ge 0.35" "ge 0.30"
premise crlf_ref.md          "ge 5000" "ge 0.35" "ge 0.15"
premise crlf_caption.md      "ge 5000" "ge 0.35" "lt 0.15"
premise crlf_headed.md       "ge 5000" "ge 0.35" "lt 0.15"
FENCE="$( run --recall=zqfence --top-k=100 --max-tokens=400000 )"
R=$R_SAVE
