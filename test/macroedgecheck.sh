#!/usr/bin/env bash
# macroedgecheck.sh — gate for the macro-edges round (function-like #define becomes a call-graph participant).
#
# The disclosed gap this closes: every graph-count legend said "a macro-generated call site ... contributes
# no edge". Post-round, a FUNCTION-LIKE `#define NAME(args) body` with a non-empty body is an indexed,
# disclosed-degraded symbol (t="macro"), the call-shaped invocation of its name carries role="macro" — NEVER
# role="call" (call-edge honesty: an expansion is not a plain call) — and the calls inside its replacement
# text produce edges FROM the macro symbol, so the graph connects through it (handler -> LOG_ERR -> logImpl).
# Object-like `#define MAXN 42` stays a non-participant on the C++ path (not even a symbol), and an
# empty-body function-like macro defines nothing callable, so it stays unindexed too.
#
# The fixture is GENERATED here (self-contained; nothing committed under test/):
#   log.h   — a MACRO-ONLY header (the ensemble.h coverage hole: pre-round it contributed ZERO symbols):
#             LOG_ERR (body calls logImpl), RETRY (body calls tryOnce through do/while+if — keyword +
#             macro-param filtering exercised), MAXN (object-like control), NOOP (empty-body control).
#   app.cpp — logImpl/tryOnce real defs; handler() invokes LOG_ERR; loopIt() invokes RETRY(tryOnce())
#             (the macro-ARGUMENT call parses as a normal call and must SURVIVE) and reads MAXN.
#   sitefix/ — MACRO-P0 (section 9): macro invocations the grammar reads as typeless declarators (brace-initialised
#             `REGISTER_FACTORY( F, B ){ "name" };`, nested braces, class-member DECLARE_LUA_FUNCTION / MOCK_METHOD, an
#             error-recovered in-function ASSIGN_OR_CO_RETURN, a C run of `;`-less EXPORT_FUNC) are uses, never defs; block-forming macros, real ALL-CAPS
#             functions and constructors stay defs.
#
# Usage:  RIPWIRE_BIN=build/ripwire bash test/macroedgecheck.sh   (or asan/ripwire)
# Exits non-zero on any failure; prints PASS/FAIL per check, ALL PASS on success.

set -u
ROOT="$( cd "$( dirname "$0" )/.." && pwd )"
BIN="${1:-${RIPWIRE_BIN:-$ROOT/build/ripwire}}"
[ "${BIN#/}" = "$BIN" ] && BIN="$ROOT/$BIN"          # allow a repo-relative RIPWIRE_BIN
TMP="$( mktemp -d )"; trap 'rm -rf "$TMP"' EXIT
FIX="$TMP/macrofix"
mkdir -p "$FIX"
fail=0
ok(){ printf '  PASS  %s\n' "$*" || { fail=1; printf '  FAIL  could not write the PASS line for: %s\n' "$*"; }; return 0; }
no(){ printf '  FAIL  %s\n' "$*"; fail=1; }

[ -x "$BIN" ] || { echo "no ripwire binary at $BIN — build first (cmake --build build -j)"; exit 2; }
cd "$ROOT"

cat >"$FIX/log.h" <<'EOF'
// macro-edges gate fixture — generated by test/macroedgecheck.sh, never committed.
// This header holds ONLY preprocessor definitions: pre-round it was symbol-empty.
#define LOG_ERR(msg) logImpl(msg, __FILE__)
#define RETRY(x) do { if( !(x) ) tryOnce(); } while(0)
#define MAXN 42
#define NOOP(x)
EOF

cat >"$FIX/app.cpp" <<'EOF'
// macro-edges gate fixture — generated by test/macroedgecheck.sh, never committed.
#include "log.h"
int logImpl(const char* m, const char* f) { return (m && f) ? 1 : 0; }
int tryOnce() { return 2; }
int handler() { LOG_ERR("boom"); return 0; }
int loopIt() { RETRY(tryOnce()); return MAXN + 1; }
EOF

echo "macroedgecheck: BIN=$BIN  CORPUS=$FIX (generated)"

verb(){ "$BIN" "$FIX" "$1" --no-cache 2>/dev/null; }
rows(){ verb "$1" | tr '>' '\n'; }   # one element per line so a row's own attributes can be grepped together

# ── 1) the macro edge, tagged honestly: --callees=handler emits the LOG_ERR row as t="macro" role="macro". ──
HC="$( rows --callees=handler )"
if printf '%s\n' "$HC" | grep -q 'n="LOG_ERR"'; then
    ok "handler() has a callee row for LOG_ERR (the macro invocation is an edge)"
else
    no "handler() has NO callee row for LOG_ERR — the macro invocation still contributes no edge"
fi
LR="$( printf '%s\n' "$HC" | grep 'n="LOG_ERR"' | head -1 )"
printf '%s' "$LR" | grep -q 't="macro"' \
    && ok "the LOG_ERR row carries t=\"macro\" (disclosed macro kind)" \
    || no "the LOG_ERR row is not t=\"macro\": ${LR:-<no row>}"
printf '%s' "$LR" | grep -q 'role="macro"' \
    && ok "the LOG_ERR row carries role=\"macro\" (edge crosses an expansion)" \
    || no "the LOG_ERR row has no role=\"macro\": ${LR:-<no row>}"
printf '%s\n' "$HC" | grep -q 'role="call"' \
    && no "--callees=handler emits a role=\"call\" row — macro edges must NEVER be labelled plain calls" \
    || ok "--callees=handler emits no role=\"call\" anywhere (call-edge honesty)"

# ── 2) the graph CONNECTS through the macro: LOG_ERR -> logImpl (body call), both directions visible. ──
rows --callees=LOG_ERR | grep -q 'n="logImpl"' \
    && ok "LOG_ERR (macro symbol) has a callee edge to logImpl (replacement-text call captured)" \
    || no "LOG_ERR has no callee edge to logImpl — the macro body's call was not captured"
rows --callers=logImpl | grep -q 'n="LOG_ERR"' \
    && ok "logImpl's callers include LOG_ERR (the macro symbol, not a dead end)" \
    || no "logImpl's callers do NOT include LOG_ERR"

# ── 3) --uses=LOG_ERR: the macro now HAS a definition (defs>=1, external gone) and the invocation site
#       carries role="macro", never role="call". ──
UU="$( verb --uses=LOG_ERR )"
printf '%s' "$UU" | grep -q 'defs="1"' \
    && ok "--uses=LOG_ERR reports defs=\"1\" (the #define is an indexed definition)" \
    || no "--uses=LOG_ERR does not report defs=\"1\": $( printf '%s' "$UU" | grep -o '<uses [^>]*' | head -1 )"
printf '%s' "$UU" | grep -q 'external="0"' \
    && ok "--uses=LOG_ERR reports external=\"0\" (no longer a phantom external)" \
    || no "--uses=LOG_ERR still claims external: $( printf '%s' "$UU" | grep -o 'external="[01]"' | head -1 )"
printf '%s' "$UU" | grep -q '<u role="macro"' \
    && ok "the invocation site carries role=\"macro\"" \
    || no "no role=\"macro\" use-site for LOG_ERR"
printf '%s' "$UU" | grep -q '<u role="call"' \
    && no "--uses=LOG_ERR still shows a role=\"call\" site — the honesty retag missed it" \
    || ok "--uses=LOG_ERR shows no role=\"call\" site"

# ── 4) macro-argument call survives + RETRY edge appears: loopIt -> tryOnce AND loopIt -> RETRY. ──
LC="$( rows --callees=loopIt )"
printf '%s\n' "$LC" | grep -q 'n="tryOnce"' \
    && ok "loopIt() keeps its edge to tryOnce (the macro-ARGUMENT call parses as a normal call)" \
    || no "loopIt() lost its tryOnce edge — macro-argument call regression"
printf '%s\n' "$LC" | grep 'n="RETRY"' | grep -q 'role="macro"' \
    && ok "loopIt() gains the RETRY edge, tagged role=\"macro\"" \
    || no "loopIt() has no role=\"macro\" RETRY row"

# ── 5) object-like + empty-body controls: MAXN and NOOP are NOT call-edge participants (C++ path). ──
printf '%s\n' "$LC" | grep -q 'n="MAXN"' \
    && no "loopIt() grew a MAXN edge — an object-like #define must not be a call-edge participant" \
    || ok "no MAXN edge from loopIt() (object-like #define stays out of the call graph)"
MAP="$TMP/map.xml"
"$BIN" "$FIX" --no-cache --top-k=100000 >"$MAP" 2>/dev/null
grep -q 'n="MAXN"' "$MAP" \
    && no "MAXN (object-like) was indexed as a symbol on the C++ path" \
    || ok "MAXN (object-like) is not indexed on the C++ path"
grep -q 'n="NOOP"' "$MAP" \
    && no "NOOP (empty-body function-like) was indexed — an empty body defines nothing callable" \
    || ok "NOOP (empty-body function-like) stays unindexed"

# ── 6) the macro-only header contributes symbols (the ensemble.h coverage hole). ──
if grep -oE '<s [^>]*' "$MAP" | grep 'log\.h' | grep -q 'n="LOG_ERR"'; then
    ok "log.h (macro-only header) contributes the LOG_ERR symbol to the map"
else
    # p= layout differs between map shapes — fall back to: the symbol row exists with t="macro".
    grep -oE '<s [^>]*n="LOG_ERR"[^>]*' "$MAP" | grep -q 't="macro"' \
        && ok "LOG_ERR is an indexed t=\"macro\" symbol (macro-only header no longer empty)" \
        || no "log.h contributed no LOG_ERR symbol — the macro-only-header hole is still open"
fi

# ── 6b) VERIFIER COLLISION (round A5 fix): a real function called in a translation unit with NO macro in
#        scope must NOT be re-tagged just because an unrelated same-named #define exists elsewhere in the
#        corpus. The retag fires only when the name is UNIQUELY a macro; a name shared with any non-macro
#        definition stays role="call" and takes the ordinary resolution ladder. Two shapes in one corpus:
#        `check` (real function WITH a body — resolves same-file, no macro row anywhere) and `check2`
#        (the verifier's exact shape: a bodiless PROTOTYPE beside the call — the site role is the claim). ──
COL="$TMP/collisionfix"
mkdir -p "$COL"
cat >"$COL/b_macro.c" <<'EOF'
#define check(x) do_something(x)
#define check2(y) something_else(y)
EOF
cat >"$COL/c_realcall.c" <<'EOF'
void check(int x) { }
void other(void) { check(10); }
EOF
cat >"$COL/d_protocall.c" <<'EOF'
void check2(int x);
void caller2(void) { check2(10); }
EOF
CU="$( "$BIN" "$COL" --uses=check --no-cache 2>/dev/null )"
printf '%s' "$CU" | grep -q '<u role="call" p="[^"]*c_realcall\.c:2"' \
    && ok "collision: the real call site keeps role=\"call\" (name is not uniquely a macro)" \
    || no "collision: the real call site lost role=\"call\": $( printf '%s' "$CU" | grep -oE '<u [^/]*/' | head -2 )"
printf '%s' "$CU" | grep -q '<u role="macro"' \
    && no "collision: a role=\"macro\" site appeared for a name shared with a real function" \
    || ok "collision: no role=\"macro\" site for the shared name"
OC="$( "$BIN" "$COL" --callees=other --no-cache 2>/dev/null | tr '>' '\n' )"
printf '%s\n' "$OC" | grep 'n="check"' | grep -q 'role="macro"' \
    && no "collision: --callees=other shows a role=\"macro\" check row (should resolve to the real fn)" \
    || ok "collision: --callees=other carries no role=\"macro\" check row"
printf '%s\n' "$OC" | grep 'n="check"' | grep -q 't="fn"' \
    && ok "collision: other() resolves check to the REAL function (t=\"fn\")" \
    || no "collision: other() did not resolve check to the real function"
C2="$( "$BIN" "$COL" --uses=check2 --no-cache 2>/dev/null )"
printf '%s' "$C2" | grep -q '<u role="call" p="[^"]*d_protocall\.c:2"' \
    && ok "collision (prototype shape): the call beside a bodiless decl keeps role=\"call\"" \
    || no "collision (prototype shape): the call site was re-tagged: $( printf '%s' "$C2" | grep -oE '<u [^/]*/' | head -2 )"

# ── 9) MACRO-P0: a macro INVOCATION the grammar reads as a typeless declarator is a use of the macro, never a function
#        definition (ingest_names.h cFamilyMacroInvocationDecl). envoy stored 1,664 such phantoms; ten brace-initialised
#        `REGISTER_FACTORY( F, B ){ "name" };` sites made the name non-unique, so the retag above skipped all 573 real
#        invocations and the #define read in=0. THE TRAP: one surviving phantom is enough to keep the name shared, so the
#        arm counts EVERY phantom (FAIL on >0) and its premise counts the invocations it saw (FAIL on zero). Keeps: a
#        block-forming test macro (TEST_F, an empty `TEST`), a block-forming macro with a real body, a real ALL-CAPS function
#        and prototype, ALL-CAPS constructors in-class and out of line. ──
SF="$TMP/sitefix"
mkdir -p "$SF"
cat >"$SF/registry.h" <<'EOF'
#pragma once
namespace Registry {
template <class F, class B> struct RegisterFactory { RegisterFactory( const char* n ) : name( n ) {} RegisterFactory() : name( "" ) {} const char* name; };
}
#define REGISTER_FACTORY( FACTORY, BASE ) static Registry::RegisterFactory<FACTORY, BASE> FACTORY##_registered
#define FACTORY_VERSION( a, b, c, ... ) a
#define DECLARE_LUA_FUNCTION( Class, Name ) int Name( int s )
#define MOCK_METHOD( ret, name, args, spec ) ret name args
#define ASSIGN_OR_CO_RETURN( lhs, expr ) lhs = expr
#define DEFINE_HANDLER( name ) int name##Handler()
struct Base {};
EOF
for i in 1 2 3 4 5 6; do
cat >"$SF/factory$i.cc" <<EOF
#include "registry.h"
namespace Ext$i {
struct Factory$i : Base { int create$i() { return $i; } };
REGISTER_FACTORY( Factory$i, Base ){ "ext.factory$i" };
struct Plain$i : Base {};
REGISTER_FACTORY( Plain$i, Base );
}
EOF
done
cat >"$SF/shapes.cc" <<'EOF'
#include "registry.h"
struct Versioned : Base {};
REGISTER_FACTORY( Versioned, Base ){ FACTORY_VERSION( 2, 5, 39, { { "build.label", "alpha" } } ) };
class Wrapper
{
public:
    DECLARE_LUA_FUNCTION( Wrapper, luaFoo );
    DECLARE_LUA_FUNCTION( Wrapper, luaBar );
    MOCK_METHOD( void, run, ( int ), ( override ) );
};
int receive();
int consume( int );
int decodeLoop()
{
    while( true )
    {
        ASSIGN_OR_CO_RETURN( auto event, co_await receive() );
        return consume( event );
    }
}
EOF
cat >"$SF/exports.c" <<'EOF'
#define EXPORT_FUNC( name ) static const char* name##_export = #name;
EXPORT_FUNC(PyAlpha)
EXPORT_FUNC(PyBeta)
EXPORT_FUNC(PyGamma)
EOF
cat >"$SF/keep.cc" <<'EOF'
#include "registry.h"
#define TEST_F( fixture, name ) void fixture##_##name()
#define TEST( suite, name ) void suite##_##name()
int COMPUTE_SUM( int a, int b );
int COMPUTE_SUM( int a, int b ) { return a + b; }
struct RGB
{
    RGB() {}
    RGB( int v ) : v_( v ) {}
    int v_ = 0;
};
struct HSV { HSV(); };
HSV::HSV() {}
TEST_F( SumTest, Adds ) { (void)COMPUTE_SUM( 1, 2 ); }
TEST( SumTest, Empty ) {}
DEFINE_HANDLER( reload ) { return COMPUTE_SUM( 3, 4 ); }
EOF
sverb(){ "$BIN" "$SF" "$1" --no-cache --legend=compact 2>/dev/null; }
# fnrows NAME: the function rows (t="fn" or t="method") --defs=NAME lists (-1 when the run printed no defs schema)
fnrows(){
    local out
    out="$( sverb "--defs=$1" )"
    printf '%s' "$out" | grep -q 'schema="ripwire.defs/v1"' || { printf -- '-1'; return; }
    printf '%s' "$out" | grep -oE '<d [^>]*t="(fn|method)"' | grep -c .
}
# 9a) premise: the invocations are there to be counted, and the #define is indexed
SITES="$( cat "$SF"/factory*.cc "$SF/shapes.cc" | grep -c 'REGISTER_FACTORY(' )"
RD="$( sverb --defs=REGISTER_FACTORY )"
if [ "$SITES" -ge 13 ] && printf '%s' "$RD" | grep -q '<d [^>]*t="macro"'; then
    ok "MACRO-P0 premise: $SITES REGISTER_FACTORY invocations in the fixture, and the #define is indexed"
else
    no "MACRO-P0 premise: sites=$SITES (want >=13) or no t=\"macro\" REGISTER_FACTORY row — the arms below would see nothing"
fi
# 9b) THE TRAP: no phantom def survives, in any of the six shapes (EXPORT_FUNC: a C run of `;`-less invocations, cpython's
#     PC/python3dll.c, where tree-sitter-c reads the previous invocation as a macro_type_specifier inside an ERROR node)
for m in REGISTER_FACTORY DECLARE_LUA_FUNCTION MOCK_METHOD ASSIGN_OR_CO_RETURN EXPORT_FUNC; do
    n="$( fnrows "$m" )"
    [ "$n" = 0 ] && ok "MACRO-P0 trap: --defs=$m lists 0 function defs (every invocation is a use)" \
        || no "MACRO-P0 trap: --defs=$m lists $n function def(s) — one phantom keeps the name shared and unbinds every invocation"
done
# 9c) every REGISTER_FACTORY invocation, brace-initialised or plain, is a role="macro" use of the #define
RU="$( sverb --uses=REGISTER_FACTORY )"
nu="$( printf '%s' "$RU" | grep -oE '<u role="macro"' | grep -c . )"
[ "$nu" -ge "$SITES" ] && [ "$SITES" -gt 0 ] && ok "MACRO-P0: --uses=REGISTER_FACTORY lists $nu role=\"macro\" sites (fixture has $SITES)" \
    || no "MACRO-P0: --uses=REGISTER_FACTORY lists $nu role=\"macro\" sites, fixture has $SITES"
printf '%s' "$RU" | grep -qE '<u role="macro" p="[^"]*factory1\.cc:4"' && printf '%s' "$RU" | grep -qE '<u role="macro" p="[^"]*shapes\.cc:3"' \
    && ok "MACRO-P0: the brace-initialised sites (factory1.cc:4, nested braces shapes.cc:3) are uses" \
    || no "MACRO-P0: a brace-initialised site is not a role=\"macro\" use"
printf '%s' "$RU" | grep -q '<u role="call"' \
    && no "MACRO-P0: a REGISTER_FACTORY site reads role=\"call\" — the name is still shared with a phantom" \
    || ok "MACRO-P0: no REGISTER_FACTORY site reads role=\"call\""
MIN="$( printf '%s' "$RD" | grep -oE '<d [^>]*t="macro"[^>]*' | grep -oE ' in="[0-9]+"' | grep -oE '[0-9]+' | head -1 )"
[ "${MIN:-0}" -gt 0 ] && ok "MACRO-P0: the REGISTER_FACTORY #define reads in=\"$MIN\" (was 0 while phantoms shared its name)" \
    || no "MACRO-P0: the REGISTER_FACTORY #define reads in=\"${MIN:-<none>}\""
# 9d) an in-function invocation (the error-recovered `co_await` shape) is a macro edge of its function, whose calls stay its own
DC="$( sverb --callees=decodeLoop | tr '>' '\n' )"
printf '%s\n' "$DC" | grep 'n="ASSIGN_OR_CO_RETURN"' | grep -q 'role="macro"' \
    && ok "MACRO-P0: decodeLoop() has a role=\"macro\" ASSIGN_OR_CO_RETURN row" \
    || no "MACRO-P0: decodeLoop() has no role=\"macro\" ASSIGN_OR_CO_RETURN row"
printf '%s\n' "$DC" | grep -q 'n="consume"' \
    && ok "MACRO-P0: decodeLoop() keeps its consume() callee" \
    || no "MACRO-P0: decodeLoop() lost its consume() callee"
# 9e) keeps: each must stay a function definition
for kv in TEST_F:1 TEST:1 COMPUTE_SUM:1 RGB:2 HSV:1 DEFINE_HANDLER:1; do
    k="${kv%%:*}"; want="${kv##*:}"
    n="$( fnrows "$k" )"
    [ "$n" = "$want" ] && ok "MACRO-P0 keep: --defs=$k lists $n function def(s)" \
        || no "MACRO-P0 keep: --defs=$k lists $n function def(s), want $want"
done

# ── 7) determinism — macro symbols/edges must be byte-stable run-to-run. ──
"$BIN" "$FIX" --no-cache >"$TMP/m1" 2>/dev/null
"$BIN" "$FIX" --no-cache >"$TMP/m2" 2>/dev/null
diff -q "$TMP/m1" "$TMP/m2" >/dev/null && ok "deterministic (macrofix map byte-identical across two runs)" \
    || { no "non-deterministic macrofix map"; diff "$TMP/m1" "$TMP/m2" | head -6; }

# ── 8) cache transparency — macro facts round-trip the incremental cache: warm == cold. ──
rm -f "$TMP/cc"
"$BIN" "$FIX" --cache="$TMP/cc" >/dev/null 2>&1
"$BIN" "$FIX" --cache="$TMP/cc" >"$TMP/warm" 2>/dev/null
"$BIN" "$FIX" --no-cache        >"$TMP/cold" 2>/dev/null
diff -q "$TMP/warm" "$TMP/cold" >/dev/null && ok "cache-transparent (macro facts round-trip: warm == cold)" \
    || { no "cache changes output (warm != cold)"; diff "$TMP/cold" "$TMP/warm" | head -6; }

[ "$fail" = 0 ] && echo "ALL PASS" || echo "FAILURES ABOVE"
exit $fail
