#!/usr/bin/env bash
# bashenvcheck.sh — the gate for --flags' SHELL ENV LANE (src/darkflags.h: harvestShellLine and friends).
#
# A Bash script has no getenv: every `$X` it expands without assigning X first is a read of its caller's
# environment. A CI contract check (fullsend-ai's bash-env-contract) joins those reads against what the caller
# supplies, and needs more than the name: whether the read DIES when X is missing (${X:?}), carries its own
# default (${X:-d}), or only asks whether X is set (${X:+w}, [[ -n "$X" ]]) — and whether an EMPTY value counts as
# missing (the `:` spelling). This gate is that contract, stated as rows.
#
# Fixture test/bashenvfix:
#   forms.sh          one name per read form: required (:? and ?), default (:-), unset-default (-), settest (:+ +
#                     -n -z, `test -z`), assign (:=), plain ($X ${X} ${#X} ${X[@]} ${X%/}), a nested default
#   writes.sh         WRITE_* names are assigned BEFORE their read (X=, export X=, readonly, declare -r, read -p,
#                     for, mapfile, printf -v, `X=1; echo $X`, local) -> ABSENT. KEEP_* are read first, or never
#                     assigned (bare `export X`) -> PRESENT, with the later write listed as a <write> row.
#                     PASS_* are PASS-THROUGH writes (`X="${X:-}"`, `: "${X:=d}"`): they shadow nothing
#   lib/shared.lib.sh assigns LIB_SET_ME, which writes.sh reads: one file's lexical order keeps the read, and the
#                     gate lists the library's write so a consumer that follows `source` can join them
#   quoting.sh        NOPE_* sit in single quotes (one line and multi-line), a comment, an escaped \$, a quoted
#                     heredoc, an ANSI-C $'…' string -> ABSENT. QUOTE_* are real expansions next to them (inside
#                     "…" with an apostrophe, inside $( … ) inside "…", an UNQUOTED heredoc body) -> PRESENT
#   ambient.sh        BASH_SOURCE PWD HOME RANDOM SHLVL HOSTTYPE -> ambient="1"; NOT_AMBIENT_SUPPLIED -> not
#   bundle.sh         opens with `# GENERATED from bundle.src.sh — DO NOT EDIT` -> skipped whole: GEN_ONLY_IN_BUNDLE
#                     ABSENT, generated_skipped="1". bundle.src.sh (prose "generated by" in its header) is read
#   paging.sh         PAGE_MANY read 3x then written 2x: both site lists page under --limit, next= lifts both
#   probe.py          a Python os.environ.get read: its row carries NO Bash attribute (other lanes keep their bytes)
#
# Usage:  test/bashenvcheck.sh   |   RIPWIRE_BIN=asan/ripwire test/bashenvcheck.sh
# Exit:   0 = clean · 1 = an arm failed · 2 = usage / missing prerequisite

set -u
ROOT="$( cd "$( dirname "$0" )/.." && pwd )"
BIN="${1:-${RIPWIRE_BIN:-$ROOT/build/ripwire}}"
[ "${BIN#/}" = "$BIN" ] && BIN="$ROOT/$BIN"
FIX="$ROOT/test/bashenvfix"
TMP="$( mktemp -d )"; trap 'rm -rf "$TMP"' EXIT
fail=0
ok(){ printf '  PASS  %s\n' "$*" || { fail=1; printf '  FAIL  could not write the PASS line for: %s\n' "$*"; }; return 0; }
no(){ printf '  FAIL  %s\n' "$*"; fail=1; }

[ -x "$BIN" ] || { echo "no ripwire binary at $BIN — build first (cmake --build build -j)"; exit 2; }
[ -d "$FIX" ] || { echo "no test/bashenvfix — fixture missing"; exit 2; }
command -v python3 >/dev/null 2>&1 || { echo "python3 is required (JSON arm)"; exit 2; }
echo "bashenvcheck: BIN=$BIN  FIX=$FIX"

"$BIN" "$FIX" --flags --no-cache --limit=50 --legend=full >"$TMP/x" 2>/dev/null
OUT="$( cat "$TMP/x" )"
gate(){ printf '%s' "$OUT" | tr '<' '\n' | grep -E "^gate name=\"$1\" " | head -1; }
body(){ printf '%s' "$OUT" | sed 's/<gate /\n<gate /g' | grep -E "^<gate name=\"$1\" " | head -1; }
has(){ [ -n "$( gate "$1" )" ]; }
row(){   # row NAME 'exact read element' — the gate exists and carries exactly that read row
    if body "$1" | grep -qF "$2"; then ok "$1: $2"; else no "$1: want $2, got: $( body "$1" | head -c 300 )"; fi
}

# ── 1. FORMS: one row per read form, with colon= / default= / test= exactly as spelled ───────────────────
row FORM_REQUIRED_COLON '<read p="forms.sh" l="5" form="required" colon="1"/>'
row FORM_REQUIRED_PLAIN '<read p="forms.sh" l="6" form="required" colon="0"/>'
row FORM_DEFAULT_COLON  '<read p="forms.sh" l="7" form="default" colon="1" default="/srv/default path"/>'
row FORM_UNSET_DEFAULT  '<read p="forms.sh" l="8" form="unset-default" colon="0" default=""/>'
row FORM_ALT_COLON      '<read p="forms.sh" l="9" form="settest" colon="1"/>'
row FORM_ALT_PLAIN      '<read p="forms.sh" l="9" form="settest" colon="0"/>'
for n in FORM_PLAIN_BARE FORM_PLAIN_BRACED FORM_PLAIN_LENGTH FORM_PLAIN_ARRAY FORM_PLAIN_TRIM; do
    row "$n" '<read p="forms.sh" l="10" form="plain"/>'
done
row FORM_TEST_N         '<read p="forms.sh" l="11" form="settest" test="n"/>'
row FORM_TEST_Z_DEFAULT '<read p="forms.sh" l="11" form="default" colon="1" default="" test="z"/>'
row FORM_TEST_BUILTIN   '<read p="forms.sh" l="14" form="settest" test="z"/>'
row FORM_ASSIGN_COLON   '<read p="forms.sh" l="15" form="assign" colon="1" default="assigned"/>'
row FORM_ASSIGN_COLON   '<write p="forms.sh" l="15"/>'
row FORM_NESTED_OUTER   'form="default" colon="1" default="${FORM_NESTED_INNER:-deep}"/>'
row FORM_NESTED_INNER   '<read p="forms.sh" l="16" form="default" colon="1" default="deep"/>'
if gate FORM_REQUIRED_COLON | grep -q 'kind="env" default="unset" dark="1" regions="0" loc="0" reads="1"'; then ok 'a Bash read is an ordinary env gate: kind="env" default="unset" dark="1" regions="0" loc="0"'; else no "Bash gate head wrong: $( gate FORM_REQUIRED_COLON )"; fi

# ── 2. WRITES: assigned before read -> the script's own state, not an env read ───────────────────────────
for n in WRITE_PLAIN WRITE_EXPORTED WRITE_READONLY WRITE_DECLARED WRITE_READ_NAME WRITE_LOOP WRITE_MAPFILE WRITE_PRINTF WRITE_SAMELINE WRITE_LOCAL; do
    if has "$n"; then no "write-before-read: $n reported as an env read: $( gate "$n" )"; else ok "write-before-read: $n is the script's own (absent)"; fi
done
row KEEP_SELF_DEFAULT '<read p="writes.sh" l="26" form="default" colon="1" default="fallback"/><read p="writes.sh" l="36" form="plain"/><write p="writes.sh" l="26"/>'
row KEEP_READ_FIRST   '<read p="writes.sh" l="27" form="plain"/><write p="writes.sh" l="28"/>'
row KEEP_BARE_EXPORT  '<read p="writes.sh" l="31" form="plain"/></gate>'
if gate KEEP_BARE_EXPORT | grep -q ' writes='; then no "a bare \`export X\` counted as a write: $( gate KEEP_BARE_EXPORT )"; else ok 'a bare `export X` publishes the inherited value: no write'; fi
row LIB_SET_ME '<read p="writes.sh" l="35" form="plain"/><write p="lib/shared.lib.sh" l="3"/>'
# A PASS-THROUGH write (`X="${X:-}"`, `: "${X:=d}"`) reads X in its own statement, so its value is still the caller's:
# the later default read stays an env read, and the write is still listed.
row PASS_NORMALISED '<read p="writes.sh" l="38" form="default" colon="1" default=""/><read p="writes.sh" l="39" form="default" colon="1" default="later-default"/><write p="writes.sh" l="38"/>'
row PASS_ASSIGNED   '<read p="writes.sh" l="40" form="assign" colon="1" default="first"/><read p="writes.sh" l="41" form="default" colon="1" default="second"/><write p="writes.sh" l="40"/>'
if gate LIB_SET_ME | grep -q ' writes="1"'; then ok 'LIB_SET_ME writes="1": the sourced library'"'"'s assignment is listed'; else no "LIB_SET_ME writes= wrong: $( gate LIB_SET_ME )"; fi

# ── 3. QUOTING: what Bash expands, and nothing it does not ───────────────────────────────────────────────
for n in NOPE_SINGLE_QUOTED NOPE_COMMENT NOPE_ESCAPED NOPE_MULTILINE_SINGLE NOPE_HEREDOC_QUOTED NOPE_HEREDOC_SPACED_QUOTED NOPE_ANSI_C; do
    if has "$n"; then no "INVENTED: $n is not expanded by Bash: $( gate "$n" )"; else ok "not expanded: $n"; fi
done
for n in QUOTE_DOUBLE_WITH_APOSTROPHE QUOTE_IN_SUBSTITUTION QUOTE_HEREDOC_UNQUOTED QUOTE_AFTER_ANSI_C; do
    if has "$n"; then ok "expanded: $n"; else no "MISSED: $n is a real expansion"; fi
done
row QUOTE_HEREDOC_UNQUOTED '<read p="quoting.sh" l="12" form="plain"/>'

# ── 4. AMBIENT: tagged, not dropped ──────────────────────────────────────────────────────────────────────
for n in BASH_SOURCE PWD HOME RANDOM SHLVL HOSTTYPE; do
    if gate "$n" | grep -q ' ambient="1"'; then ok "ambient: $n"; else no "ambient: $n not tagged: $( gate "$n" )"; fi
done
if gate NOT_AMBIENT_SUPPLIED | grep -q ' ambient='; then no "NOT_AMBIENT_SUPPLIED wrongly tagged ambient"; else ok "not ambient: NOT_AMBIENT_SUPPLIED"; fi

# ── 5. GENERATED: a bundle with a GENERATED … DO NOT EDIT banner is skipped whole, and disclosed ─────────
if has GEN_ONLY_IN_BUNDLE; then no "generated bundle harvested: $( gate GEN_ONLY_IN_BUNDLE )"; else ok 'generated: bundle.sh skipped (GEN_ONLY_IN_BUNDLE absent)'; fi
if gate GEN_SHARED | grep -q 'reads="1" p="bundle.src.sh" l="4"'; then ok 'generated: GEN_SHARED comes from bundle.src.sh only (its "generated by" prose is not a banner)'; else no "GEN_SHARED wrong: $( gate GEN_SHARED )"; fi
if printf '%s' "$OUT" | grep -q '<flags gates="[0-9]*" [^>]* files="9" generated_skipped="1"'; then ok 'root: files="9" still counts the bundle, generated_skipped="1" discloses it'; else no "root wrong: $( printf '%s' "$OUT" | grep -oE '<flags [^>]*>' )"; fi

# ── 6. OTHER LANES KEEP THEIR BYTES ──────────────────────────────────────────────────────────────────────
row PY_SWITCH '<read p="probe.py" l="4"/></gate>'
"$BIN" "$ROOT/test/flagsfix" --flags --no-cache --legend=full >"$TMP/nf" 2>/dev/null
if ! grep -q '<flags gates="[1-9]' "$TMP/nf"; then
    no "test/flagsfix produced no gate report — the no-BASH-legend arm below would pass vacuously"
elif grep -q '<!-- BASH:' "$TMP/nf"; then
    no "a corpus with no shell file grew the BASH legend comment"
else
    ok 'no shell rows -> no BASH legend comment (a non-shell answer is byte-identical to before)'
fi
if printf '%s' "$OUT" | grep -q '<!-- BASH: .*form=.*colon=.*default=.*test=.*writes=.*ambient=.*generated_skipped='; then ok 'legend: the BASH comment defines form= colon= default= test= writes= ambient= generated_skipped='; else no 'legend: the BASH comment is missing or does not define every new attribute'; fi

# ── 7. PAGING: the read and write site lists page together; next= lifts both ─────────────────────────────
"$BIN" "$FIX" --flags=PAGE_MANY --no-cache --limit=1 --legend=full >"$TMP/p" 2>/dev/null
P="$( cat "$TMP/p" )"
if printf '%s' "$P" | grep -q 'reads="3" p="paging.sh" l="3" shown_reads="1" reads_capped="1" writes="2" shown_writes="1" writes_capped="1">'; then ok 'paging: reads="3" shown_reads="1" / writes="2" shown_writes="1", both capped'; else no "paging head wrong: $( printf '%s' "$P" | grep -oE '<gate [^>]*>' )"; fi
if printf '%s' "$P" | grep -q '<more reads="2"/><write p="paging.sh" l="6"/><more writes="1"/></gate>'; then ok 'paging: <more reads="2"/> and <more writes="1"/> name the remainder'; else no "paging rows wrong: $( printf '%s' "$P" | sed 's/.*<gate /<gate /' | head -c 400 )"; fi
if printf '%s' "$P" | grep -q 'next="--flags --limit=3"'; then ok 'paging: next="--flags --limit=3" lifts both lists'; else no "next= wrong: $( printf '%s' "$P" | grep -oE 'next="[^"]*"' )"; fi

# ── 8. JSON: the same rows, keys = the XML attribute names, booleans for the 0/1 flags ──────────────────
"$BIN" "$FIX" --flags --json --no-cache --limit=50 >"$TMP/j" 2>"$TMP/je"; rc=$?
if [ "$rc" -eq 0 ]; then ok "--flags --json exits 0"; else no "--flags --json exit=$rc: $( head -c 200 "$TMP/je" )"; fi
python3 - "$TMP/j" "$TMP/x" <<'PY'; rc_py=$?
import json, re, sys
doc = json.load( open( sys.argv[1] ) )
xml = open( sys.argv[2] ).read()
bad = []
if doc.get( "schema" ) != "ripwire.flags/v1": bad.append( "schema" )
if doc.get( "generated_skipped" ) != 1: bad.append( "generated_skipped" )
xmlNames = re.findall( r'<gate name="([^"]*)"', xml )
if [ g["name"] for g in doc["gate"] ] != xmlNames: bad.append( "gate order/names differ from the XML" )
if doc["gates"] != len( doc["gate"] ): bad.append( "gates= count" )
by = { g["name"]: g for g in doc["gate"] }
def read0( n ): return by[n]["read"][0]
want = {
    "FORM_REQUIRED_COLON": { "form": "required", "colon": True },
    "FORM_REQUIRED_PLAIN": { "form": "required", "colon": False },
    "FORM_DEFAULT_COLON":  { "form": "default", "colon": True, "default": "/srv/default path" },
    "FORM_UNSET_DEFAULT":  { "form": "unset-default", "colon": False, "default": "" },
    "FORM_ALT_COLON":      { "form": "settest", "colon": True },
    "FORM_TEST_N":         { "form": "settest", "test": "n" },
    "FORM_TEST_Z_DEFAULT": { "form": "default", "colon": True, "default": "", "test": "z" },
    "FORM_ASSIGN_COLON":   { "form": "assign", "colon": True, "default": "assigned" },
    "FORM_PLAIN_BARE":     { "form": "plain" },
}
for n, w in want.items():
    got = { k: v for k, v in read0( n ).items() if k not in ( "p", "l" ) }
    if got != w: bad.append( f"{n}: {got} != {w}" )
if "form" in read0( "PY_SWITCH" ): bad.append( "PY_SWITCH carries a Bash form" )
if by["PWD"].get( "ambient" ) is not True or "ambient" in by["NOT_AMBIENT_SUPPLIED"]: bad.append( "ambient" )
if by["LIB_SET_ME"].get( "writes" ) != 1 or by["LIB_SET_ME"]["write"] != [ { "p": "lib/shared.lib.sh", "l": 3 } ]: bad.append( "LIB_SET_ME writes" )
if by["FORM_REQUIRED_COLON"]["dark"] is not True: bad.append( "dark is not a boolean" )
for b in bad: print( "    JSON:", b )
sys.exit( 1 if bad else 0 )
PY
if [ "$rc_py" -eq 0 ]; then ok "JSON: same gates as the XML, forms/colon/default/test/ambient/writes mirrored"; else no "JSON arm failed (see above)"; fi
"$BIN" "$FIX" --flags=PAGE_MANY --json --no-cache --limit=1 >"$TMP/jp" 2>/dev/null
python3 - "$TMP/jp" <<'PY'; rc_py=$?
import json, sys
d = json.load( open( sys.argv[1] ) ); g = d["gate"][0]
sys.exit( 0 if ( g["shown_reads"], g["reads_capped"], g["more_reads"], g["shown_writes"], g["writes_capped"], g["more_writes"], d["next"] )
             == ( 1, True, 2, 1, True, 1, "--flags --json --limit=3" ) else 1 )
PY
if [ "$rc_py" -eq 0 ]; then ok 'JSON paging: shown_reads/reads_capped/more_reads, shown_writes/writes_capped/more_writes, next'; else no "JSON paging wrong: $( head -c 400 "$TMP/jp" )"; fi

# ── 9. determinism, G4 ───────────────────────────────────────────────────────────────────────────────────
"$BIN" "$FIX" --flags --no-cache --limit=50 --legend=full >"$TMP/x2" 2>/dev/null
if cmp -s "$TMP/x" "$TMP/x2"; then ok "deterministic: two XML runs byte-identical"; else no "XML non-deterministic"; fi
"$BIN" "$FIX" --flags --json --no-cache --limit=50 >"$TMP/j2" 2>/dev/null
if cmp -s "$TMP/j" "$TMP/j2"; then ok "deterministic: two JSON runs byte-identical"; else no "JSON non-deterministic"; fi
"$BIN" "$FIX" --flags --no-cache >"$TMP/xc" 2>/dev/null
"$BIN" "$FIX" --flags --no-cache >"$TMP/xc2" 2>/dev/null
if cmp -s "$TMP/xc" "$TMP/xc2"; then ok "deterministic: two default-posture runs byte-identical"; else no "default posture non-deterministic"; fi
if command -v xmllint >/dev/null 2>&1; then
    if xmllint --noout "$TMP/x" 2>/dev/null && xmllint --noout "$TMP/xc" 2>/dev/null; then ok "xml well-formed (full + default legend)"; else no "xml malformed"; fi
else
    ok "xml well-formed (xmllint absent — skipped)"
fi
if [ "$( tr -cd '\n' <"$TMP/x" | wc -c | tr -d ' ' )" -le 1 ]; then ok "G4: no newline inside the document"; else no "G4: stray newlines in the XML"; fi

[ "$fail" -eq 0 ] && echo "ALL PASS" || { echo "SOME CHECKS FAILED"; exit 1; }
