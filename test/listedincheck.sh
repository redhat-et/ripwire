#!/usr/bin/env bash
# listedincheck.sh — LISTED-IN on a --for answer (lane manifest-noncode; src/listedin.h; CONTRIBUTING family 10 slice 10c).
#
# THE CONTRACT THIS PINS (arms tagged [P] are RED on the pre-change binary 251ac97c; [G] arms are twins and near-miss negatives
# that hold on both binaries and must keep holding — PROCESS rule 4, no gate erosion):
#
#   TRIGGER  CLI --for (XML, default regime) whose task has a creation word and whose ranked head shows a file that a build,
#            package or registry manifest at the root or above it lists by a bounded path token.
#   WHAT     <listed p= of= by=path|dir [also=]><ln l=>LINE</ln>…</listed> after the tail, each line byte-exact (XML-escaped)
#            after the less-indented line it sits under.
#   NOT      a task without a creation word, a glob listing, a comment line, --json, RIPWIRE_NO_LISTED_IN=1.
#
# Arms:
#   (D1 holds on 251ac97c — no <listed> at all — and is RED on f8399b64, which matched directory tokens in make files)
#   A1 [P] automake: "new widget" → <listed p="Makefile.am" of="widget-alpha.c" by="path"> with ln l=4 (the SOURCES opener) and l=5
#   A2 [G] a comment line naming a file (`# widget-old.c is gone`) is not a listing: no ln l="3", widget-old.c in no also=
#   A3 [P] package manifests: package.json by="dir" l=8,9 (the ./cors exports key + its build output), jsr.json by="path" l=2,4
#   A4 [G] segment-bounded: src/middleware/log/index.ts is never named by `middleware/logger` lines (absent from of=/also=)
#   A5 [G] a creation word inside an identifier is not one: "addWidget alpha run" and "widget_new_alpha run" carry no <listed>
#   A6 [P] an all-caps creation word is a word, not a camel boundary: "NEW widget" carries <listed p="Makefile.am"
#   S1 [P] a registry needs a sibling: deno.json names ONE shown file (its "exports") and carries no <listed>; package.json names two (also=)
#   D1 [G] a Makefile naming the shown middleware DIRECTORIES as command arguments carries no <listed> (make lists sources by file path)
#   P1 [P] a directory token names that directory, not a deeper one: "./dist/middleware/cors/internal/helpers.js" (l=11) is not printed
#   V1 [G] vendored: a shown file under bower_components/ with its own package.json listing it carries no <listed> for that manifest
#   B1 [G, RED on 2ccc0a30] a DIRECTORY named BUILD (and, on a case-insensitive file system, build/) beside the manifests is not read: no "ignoring BUILD" warning on stderr
#      (the directory is created at RUN time in a copy of the fixtures: .gitignore `build*/` keeps it out of the tree, so a committed one never reached CI)
#   M1 [G] a Makefile beside Makefile.am is not read   G1 [G] a Makefile that says "generated by" carries gen=1
#   H1 [P] a manifest line naming legacy/x.c or old.x.c is not the listing of the root x.c; twin: ./x.c and $(srcdir)/x.c still list
#   H2 [P] package a's package.json never lists a file of package b (monorepo); H3 [P] a Bazel exclude = [...] list is not a listing, srcs = [...] is
#   H5 [P] a CMake #[[ ]] block, list(REMOVE_ITEM) and a trailing # comment are not listings, the live stanza is
#   ST1 [P] siblings count only inside the SAME top-level stanza (add_library / add_executable on two lines are two)
#   RP1 [P-mutant] the <listed> re-pick from the rows <sigs> emitted (verbs_for.h): --pack-budget-bytes=1 leaves one row, so no <listed>, no clause
#   RA [P] a subdirectory manifest's $(top_srcdir)/x.c, ${CMAKE_SOURCE_DIR}/x.c, //:x.cc names the ROOT x.c, never its own sub/x.c
#       (runtime variants of sb / lbl; twins ${CMAKE_CURRENT_SOURCE_DIR}/ and $(srcdir)/ still list sub/x.c)
#   DD1 [P] a subdirectory manifest's bare x.c names ITS x.c, never the root one (sb, lbl)   DD2 [P] the root package.json never lists a file in a NESTED package (np; twin np2)
#   DD3 [P] "!./x" is an exclusion (neg; twin neg2)   DD4 [P] a //pkg:x.cc label names package pkg (lbl; twin lbl2: a bare :x.cc lists)
#   Z1 [P] a manifest above the crawl size ceiling is not read
#   N1 [G] no creation word ("widget alpha"): no <listed>, no clause
#   N2 [G] a glob listing ($(wildcard *.c)) is a floor: no <listed>
#   N3 [G] prefix identity: the answer minus <listed> and its clause, est_tokens masked, equals RIPWIRE_NO_LISTED_IN=1
#   N4 [G] --json carries no listed
#   L1 [P] the clause rides (compact and full) and defines every attribute <listed>/<ln> carry, as whole names in the clause alone
#   X1 [G] determinism  X2 [G] xmllint well-formed (when xmllint exists)  X3 [G] no "--" inside the legend comment
#
# Usage:  bash test/listedincheck.sh [BIN]   |   RIPWIRE_BIN=asan/ripwire bash test/listedincheck.sh
# BIN is $1, else RIPWIRE_BIN, else build/ripwire; the first output line names the binary used. Exits non-zero on any failure.

set -u
ROOT="$( cd "$( dirname "$0" )/.." && pwd )"
. "$ROOT/test/lib/clean-env.sh"
unset RIPWIRE_NO_LISTED_IN
BIN="${1:-${RIPWIRE_BIN:-$ROOT/build/ripwire}}"
[ "${BIN#/}" = "$BIN" ] && BIN="$ROOT/$BIN"
echo "listedincheck: BIN=$BIN"
fail=0
ok(){ printf '  PASS  %s\n' "$*" || { fail=1; printf '  FAIL  could not write the PASS line for: %s\n' "$*"; }; return 0; }
no(){ printf '  FAIL  %s\n' "$*"; fail=1; }

[ -x "$BIN" ] || { echo "no ripwire binary at $BIN — build first"; exit 2; }
command -v python3 >/dev/null 2>&1 || { echo "python3 required"; exit 2; }
FX="$ROOT/test/listedinfix"
[ -f "$FX/am/Makefile.am" ] && [ -f "$FX/pkg/package.json" ] && [ -f "$FX/pkg/jsr.json" ] && [ -f "$FX/glob/Makefile" ] || { echo "fixture test/listedinfix missing"; exit 2; }
T="$( mktemp -d )"; trap 'rm -rf "$T"' EXIT
H="$T/home"; mkdir -p "$H"
# The fixtures run from a COPY: B1's directory named BUILD cannot be committed (.gitignore `build*/` matches it, case-folded), so it
# is created here, at runtime, and the premise is checked (a gate whose premise is missing passes on any binary).
cp -R "$FX" "$T/fx" && FX="$T/fx" || { echo "cannot copy the fixtures"; exit 2; }
mkdir -p "$FX/am/BUILD" && echo "a directory named BUILD: not a Bazel file" >"$FX/am/BUILD/README.txt"
mkdir -p "$FX/am/build" 2>/dev/null   # the lowercase twin where the file system tells them apart (a no-op where it does not)

run(){   # dir out task [extra args…]
    local d="$1" o="$2" t="$3"; shift 3
    ( cd "$FX/$d" || exit 1; HOME="$H" "$BIN" "$FX/$d" --no-cache "--for=$t" "$@" </dev/null >"$o" 2>"$o.err" )
    local rc=$?
    [ "$rc" -eq 0 ] && [ -s "$o" ] || { no "run $d '$t' $*: rc=$rc or empty output ($(head -c 200 "$o.err"))"; return 1; }
    return 0
}
has(){ grep -qF -- "$2" "$1"; }

# ---- A1 / A2 / A5
if run am "$T/a1" "new widget"; then
    if has "$T/a1" '<listed p="Makefile.am" of="widget-alpha.c" by="path"' && has "$T/a1" '<ln l="4">dist_demo_SOURCES = \</ln>' && has "$T/a1" '<ln l="5">&#9;widget-alpha.c \</ln>'; then
        ok "A1 Makefile.am lists widget-alpha.c (by=path) with its SOURCES opener l=4 and l=5"
    else no "A1 expected <listed p=\"Makefile.am\" of=\"widget-alpha.c\" by=\"path\"> with ln l=4/l=5: $(grep -o '<listed .*</listed>' "$T/a1" | head -c 400)"; fi
    if ! has "$T/a1" '<ln l="3">' && ! grep -o '<listed [^>]*>' "$T/a1" | grep -qF 'widget-old.c'; then ok "A2 a comment line naming widget-old.c is not a listing"
    else no "A2 the comment line was taken as a listing"; fi
fi
for t5 in "addWidget alpha run" "widget_new_alpha run"; do   # [G] identifiers; A6 below is the all-caps twin that DOES fire
    if run am "$T/a5" "$t5"; then
        if ! has "$T/a5" '<listed'; then ok "A5 identifier subtoken is not a creation word ($t5)"; else no "A5 '$t5' fired <listed>"; fi
    fi
done

if run am "$T/a6" "NEW widget"; then
    if has "$T/a6" '<listed p="Makefile.am"'; then ok "A6 an all-caps creation word (NEW widget) fires"; else no "A6 'NEW widget' carried no <listed>"; fi
fi

# ---- A3 / A4
if run pkg "$T/a3" "new middleware"; then
    if has "$T/a3" '<listed p="package.json" of="src/middleware/cors/index.ts" by="dir" also="src/middleware/logger/index.ts"' && has "$T/a3" '<ln l="8">    &quot;./cors&quot;: {</ln>' \
       && has "$T/a3" '<ln l="9">      &quot;import&quot;: &quot;./dist/middleware/cors/index.js&quot;</ln>'; then ok "A3 package.json exports stanza by=dir l=8,9 (logger in also=)"
    else no "A3 package.json stanza missing: $(grep -o '<listed .*</listed>' "$T/a3" | head -c 500)"; fi
    if has "$T/a3" '<listed p="jsr.json" of="src/middleware/cors/index.ts" by="path"' && has "$T/a3" '<ln l="2">  &quot;exports&quot;: {</ln>' \
       && has "$T/a3" '<ln l="4">    &quot;./cors&quot;: &quot;./src/middleware/cors/index.ts&quot;</ln>'; then ok "A3 jsr.json exports line by=path l=2,4"
    else no "A3 jsr.json line missing"; fi
    if ! grep -o '<listed [^>]*>' "$T/a3" | grep -qF 'middleware/log/index.ts'; then ok "A4 middleware/log is not named by middleware/logger lines"
    else no "A4 segment bound broken: middleware/log/index.ts listed"; fi
fi

if ! has "$T/a3" '<listed p="deno.json"' && grep -o '<listed p="package.json"[^>]*>' "$T/a3" | grep -qF 'also="src/middleware/logger/index.ts'; then ok "S1 one-file manifest (deno.json) not printed; package.json carries its sibling in also="
else no "S1 sibling rule: $(grep -o '<listed [^>]*>' "$T/a3")"; fi
if has "$T/a3" '<listed p="package.json"' && ! has "$T/a3" '<ln l="11">'; then ok "P1 a deeper directory under the shown one is not its listing"; else no "P1 deeper-directory line printed or package.json missing"; fi
if ! has "$T/a3" '<listed p="Makefile"'; then ok "D1 a Makefile's directory arguments are not a listing"; else no "D1 Makefile directory arguments were listed"; fi
if grep -o '<listed [^>]*>' "$T/a3" | grep -qF 'bower_components'; then no "V1 a vendored copy's own manifest was listed"; else ok "V1 vendored bower_components/ manifest not listed"; fi

if [ ! -d "$FX/am/BUILD" ]; then no "B1 premise: the BUILD directory fixture was not created"
elif ! grep -q 'ignoring BUILD' "$T/a1.err"; then ok "B1 a BUILD directory is not opened as a manifest (stderr clean)"; else no "B1 stderr: $(grep 'ignoring BUILD' "$T/a1.err" | head -c 200)"; fi

# ---- M1 / G1 / H1-H5 / ST1 / RP1 / Z1  (review fix round: wrong-file, other-package, excluded and commented names are never "listed")
lst(){ grep -o '<listed [^>]*>' "$1"; }
if has "$T/a1" '<listed p="Makefile.am"' && ! lst "$T/a1" | grep -qF 'p="Makefile"'; then ok "M1 a configure-written Makefile beside Makefile.am is not read"; else no "M1 Makefile read beside Makefile.am: $(lst "$T/a1")"; fi
if run gen "$T/g1" "new widget"; then
    if lst "$T/g1" | grep -F 'p="Makefile"' | grep -qF 'gen="1"'; then ok "G1 a Makefile that says it is generated carries gen=1"; else no "G1 expected <listed p=\"Makefile\" gen=\"1\">: $(lst "$T/g1")"; fi
fi
if run h1 "$T/h1" "new widget"; then
    if ! has "$T/h1" '<listed'; then ok "H1 legacy/widget-alpha.c and old.widget-alpha.c are not the listing of the root widget-alpha.c"; else no "H1 a different file of the same basename was listed: $(lst "$T/h1")"; fi
fi
if run h1t "$T/h1t" "new widget"; then
    if lst "$T/h1t" | grep -F 'p="Makefile.am"' | grep -qF 'widget-beta.c' && lst "$T/h1t" | grep -F 'of="widget-alpha.c"' | grep -qF 'by="path"'; then ok "H1 twin ./widget-alpha.c and \$(srcdir)/widget-beta.c still list"; else no "H1 twin: ./ or \$(srcdir)/ no longer matches: $(lst "$T/h1t")"; fi
fi
if run h2 "$T/h2" "new middleware"; then
    if ! lst "$T/h2" | grep -F 'p="packages/a/package.json"' | grep -qF 'packages/b/' && lst "$T/h2" | grep -F 'p="packages/a/package.json"' | grep -qF 'of="packages/a/'; then ok "H2 package a's manifest lists package a's files, never package b's"; else no "H2 monorepo: $(lst "$T/h2")"; fi
fi
if run h3 "$T/h3" "new widget"; then
    if ! lst "$T/h3" | grep -qE 'widget_(alpha|beta)' && lst "$T/h3" | grep -F 'p="BUILD"' | grep -qE 'widget_(gamma|delta)'; then ok "H3 an exclude = [...] list is not a listing; the srcs = [...] twin is"; else no "H3 exclude list: $(lst "$T/h3")"; fi
fi
if run h5 "$T/h5" "new widget"; then
    if ! lst "$T/h5" | grep -qE 'widget-(alpha|beta|gamma|delta|eta)' && lst "$T/h5" | grep -F 'p="CMakeLists.txt"' | grep -F 'widget-epsilon' | grep -qF 'widget-zeta'; then ok "H5 bracket comment, REMOVE_ITEM and trailing # comments are not listings; the live stanza is"; else no "H5 comments/removals: $(lst "$T/h5")"; fi
fi
if run st "$T/st" "new widget"; then
    if ! has "$T/st" '<listed'; then ok "ST1 two names in two stanzas (add_library / add_executable) are not siblings"; else no "ST1 siblings from different stanzas: $(lst "$T/st")"; fi
fi
# ---- DD1-DD4 (delta-review fix round 2: a name resolves from the manifest's OWN directory; nested package, `!./` and `//pkg:` label)
outside(){   # file p-value prefix: every of=/also= name of the <listed p=PVALUE> elements starts with PREFIX (none = pass)
    lst "$1" | grep -F "p=\"$2\"" | python3 -c "
import re, sys
bad = []
for l in sys.stdin:
    for a in re.findall(r' (?:of|also)=\"([^\"]*)\"', l):
        bad += [n for n in a.split(',') if not n.startswith(sys.argv[1])]
sys.exit(1 if bad else 0)" "$3"
}
if run sb "$T/sb" "new widget"; then
    if outside "$T/sb" 'sub/Makefile.am' 'sub/'; then ok "DD1 sub/Makefile.am's bare widget-alpha.c is sub/widget-alpha.c: the root file and the other widget-*.c are never claimed"; else no "DD1 a subdirectory manifest claimed a file outside its directory: $(lst "$T/sb")"; fi
fi
if run lbl "$T/lbl" "new widget"; then
    if outside "$T/lbl" 'other/BUILD' 'other/'; then ok "DD1 other/BUILD's exports_files lists other/widget_*.cc, never the root files"; else no "DD1 other/BUILD claimed a root file: $(lst "$T/lbl")"; fi
    if ! lst "$T/lbl" | grep -qF 'p="BUILD"'; then ok "DD4 the label //other:widget_alpha.cc names package other, not the root widget_alpha.cc"; else no "DD4 a //pkg: label was listed as the root file: $(lst "$T/lbl")"; fi
fi
cp -R "$FX/lbl" "$FX/lbl2" && sed -i.bak 's#//other:#:#' "$FX/lbl2/BUILD" && rm -f "$FX/lbl2/BUILD.bak"
if run lbl2 "$T/lbl2" "new widget"; then
    if lst "$T/lbl2" | grep -F 'p="BUILD"' | grep -qF 'of="widget_alpha.cc"'; then ok "DD4 twin: a bare :widget_alpha.cc label still lists the package's own file"; else no "DD4 twin: a bare label no longer lists: $(lst "$T/lbl2")"; fi
fi
if run np "$T/np" "new middleware"; then
    if ! lst "$T/np" | grep -F 'p="package.json"' | grep -qF 'packages/b/'; then ok "DD2 the root package.json's directory tails never reach a file inside a nested package"; else no "DD2 the root package.json listed a nested package's file: $(lst "$T/np")"; fi
fi
cp -R "$FX/np" "$FX/np2" && rm -f "$FX/np2/packages/b/package.json"
if run np2 "$T/np2" "new middleware"; then
    if lst "$T/np2" | grep -F 'p="package.json"' | grep -qF 'packages/b/'; then ok "DD2 twin: without the nested package.json the root one lists by directory"; else no "DD2 twin: the root package.json no longer lists packages/b: $(lst "$T/np2")"; fi
fi
if run neg "$T/neg" "new middleware"; then
    if ! has "$T/neg" '<listed'; then ok "DD3 \"!./src/...\" in package.json files is an exclusion, never a listing"; else no "DD3 a ./ negation was listed: $(lst "$T/neg")"; fi
fi
cp -R "$FX/neg" "$FX/neg2" && sed -i.bak 's#"!\./#"./#' "$FX/neg2/package.json" && rm -f "$FX/neg2/package.json.bak"
if run neg2 "$T/neg2" "new middleware"; then
    if lst "$T/neg2" | grep -F 'p="package.json"' | grep -qF 'of="src/middleware/'; then ok "DD3 twin: \"./src/...\" without the ! still lists"; else no "DD3 twin: ./ no longer lists: $(lst "$T/neg2")"; fi
fi
# ---- RA (train 42a, rv-manifest-delta2 E1): a SUBDIRECTORY manifest's ROOT-anchored spelling names the ROOT file, never its own sub/x.c.
# Runtime variants of sb (Makefile.am / CMakeLists.txt in sub/) and lbl (other/BUILD); twins keep the manifest-relative anchors listing.
claims(){ lst "$1" | grep -F "p=\"$2\"" | grep -qE " (of|also)=\"$3"; }   # file p-value prefix: a <listed p=PVALUE> claims a name under PREFIX
mkra(){   # name manifest-file text: sb copy whose sub/ holds ONLY that manifest
    cp -R "$FX/sb" "$FX/$1" && rm -f "$FX/$1/sub/Makefile.am" && printf '%b' "$3" >"$FX/$1/sub/$2"
}
mkra ra1 Makefile.am 'bin_PROGRAMS = demo\ndemo_SOURCES = \\\n\t$(top_srcdir)/widget-alpha.c \\\n\t$(top_srcdir)/widget-beta.c\n'
mkra ra2 CMakeLists.txt 'add_library(w\n    ${CMAKE_SOURCE_DIR}/widget-alpha.c\n    ${CMAKE_SOURCE_DIR}/widget-beta.c)\n'
mkra ra4 CMakeLists.txt 'add_library(w\n    ${CMAKE_CURRENT_SOURCE_DIR}/widget-alpha.c\n    ${CMAKE_CURRENT_SOURCE_DIR}/widget-beta.c)\n'
mkra ra5 Makefile.am 'bin_PROGRAMS = demo\ndemo_SOURCES = \\\n\t$(srcdir)/widget-alpha.c \\\n\t$(srcdir)/widget-beta.c\n'
cp -R "$FX/lbl" "$FX/ra3" && rm -f "$FX/ra3/BUILD" && printf 'filegroup(\n    name = "w",\n    srcs = [\n        "//:widget_alpha.cc",\n        "//:widget_beta.cc",\n    ],\n)\n' >"$FX/ra3/other/BUILD"
grep -qF '$(top_srcdir)/widget-alpha.c' "$FX/ra1/sub/Makefile.am" && grep -qF '"//:widget_alpha.cc"' "$FX/ra3/other/BUILD" || no "RA premise: the runtime manifests were not written"
for v in "ra1 sub/Makefile.am sub/ \$(top_srcdir)/" "ra2 sub/CMakeLists.txt sub/ \${CMAKE_SOURCE_DIR}/" "ra3 other/BUILD other/ //:"; do
    set -- $v
    if run "$1" "$T/$1" "new widget"; then
        if ! claims "$T/$1" "$2" "$3"; then ok "RA $2's $4x names the ROOT file: never listed as $3x"; else no "RA $2's $4x was claimed as the listing of $3x: $(lst "$T/$1")"; fi
    fi
done
for v in "ra4 sub/CMakeLists.txt \${CMAKE_CURRENT_SOURCE_DIR}/" "ra5 sub/Makefile.am \$(srcdir)/"; do
    set -- $v
    if run "$1" "$T/$1" "new widget"; then
        if lst "$T/$1" | grep -F "p=\"$2\"" | grep -qF 'of="sub/widget-'; then ok "RA twin: $2's $3x still lists sub/x"; else no "RA twin: $2's $3x no longer lists sub/x: $(lst "$T/$1")"; fi
    fi
done
# RP1: the manifest is picked from the rows <sigs> EMITS (epmanifestcheck R1-R3): one emitted row = no sibling = no <listed>, no clause
if run am "$T/rp1" "new widget" --pack-budget-bytes=1; then
    if grep -q '<sigs shown="1" ' "$T/rp1" && ! has "$T/rp1" '<listed' && ! has "$T/rp1" '; listed p= of='; then ok "RP1 one <sigs> row: no <listed> and no clause over rows <sigs> dropped"; else no "RP1 <listed> rides over a row <sigs> dropped: $(lst "$T/rp1")"; fi
fi
# Z1: a manifest above the crawl size ceiling (4 MB) is not read
cp -R "$FX/am" "$FX/big" && rm -f "$FX/big/Makefile" && python3 -c "
import sys
p=sys.argv[1]; t=open(p).read(); open(p,'w').write(t+'# '+'x'*(4*1024*1024+100)+'\n')" "$FX/big/Makefile.am"
if run big "$T/z1" "new widget"; then
    if ! has "$T/z1" '<listed'; then ok "Z1 a Makefile.am above the 4 MB crawl ceiling is not read"; else no "Z1 an over-ceiling manifest was read"; fi
fi

# Y1 (CR 4419328415): a manifest line holding only "\r" (a "\r\r\n" ending: forEachLine drops one \r, trim drops the rest, indentOf keeps it)
#    reaches the continuation test with an EMPTY trimmed view; the answer is the same listing as the file without that line, rc 0
cp -R "$FX/am" "$FX/crlf" && printf '\r\r\n' >>"$FX/crlf/Makefile.am"
if run crlf "$T/y1" "new widget"; then
    if [ "$( lst "$T/y1" | sort )" = "$( lst "$T/a1" | sort )" ] && has "$T/y1" '<listed p="Makefile.am" of="widget-alpha.c" by="path"'; then
        ok "Y1 a manifest line of only \\r (a \\r\\r\\n ending) is read as a blank line: the same listing, no crash"
    else no "Y1 the \\r\\r\\n manifest changed the listing: $( lst "$T/y1" ) vs $( lst "$T/a1" )"; fi
fi
# F1 (CR 4419328407): the *.bzl cap (kListedBzlPerDir = 8) is disclosed on the surviving element; 8 files (twin) and the earlier arms are not
mkbzl(){   # dir count: a root with a BUILD that lists both shown files and COUNT *.bzl files beside it
    mkdir -p "$FX/$1" && cp "$FX/lbl/widget_alpha.cc" "$FX/lbl/widget_beta.cc" "$FX/$1/" \
        && printf 'cc_library(\n    name = "w",\n    srcs = [\n        "widget_alpha.cc",\n        "widget_beta.cc",\n    ],\n)\n' >"$FX/$1/BUILD" || return 1
    local n; for n in $( seq 1 "$2" ); do printf '# rules\nX%s = 1\n' "$n" >"$FX/$1/r$n.bzl"; done
}
if mkbzl bzl9 9 && mkbzl bzl8 8; then
    if run bzl9 "$T/f1" "new widget" && run bzl8 "$T/f1t" "new widget"; then
        if lst "$T/f1" | grep -F 'p="BUILD"' | grep -qF 'files_capped="1"' && has "$T/f1" '; listed p= of= by=' && ! lst "$T/f1t" | grep -qF 'files_capped' && lst "$T/f1t" | grep -qF 'p="BUILD"'; then
            ok "F1 a 9th *.bzl file is not read and the <listed> says so (files_capped=1); the 8-file twin lists and does not"
        else no "F1 bzl cap: 9 files: [$( lst "$T/f1" )] 8 files: [$( lst "$T/f1t" )]"; fi
    fi
else no "F1 premise: the *.bzl fixtures were not created"; fi
if ! lst "$T/a1" | grep -qF 'files_capped' && ! lst "$T/a3" | grep -qF 'files_capped' && ! lst "$T/g1" | grep -qF 'files_capped'; then ok "F0 no cap fired on the standard fixtures: no files_capped"; else no "F0 files_capped on a fixture no cap fires on"; fi
# F2: the shown-file cap (kListedShownFiles = 16): 20 files whose names the task matches, one registry listing them all
mkdir -p "$FX/sf20" && printf 'dist_demo_SOURCES = \\\n' >"$FX/sf20/Makefile.am"
for n in $( seq -w 1 20 ); do
    printf 'int widget_%s_init( void ) { return %s; }\n' "$n" "$n" >"$FX/sf20/widget-$n.c"
    printf '\twidget-%s.c \\\n' "$n" >>"$FX/sf20/Makefile.am"
done
