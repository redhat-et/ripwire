#!/usr/bin/env python3
"""packs_build.py — src/legendpacks.h is a BUILD PRODUCT of bench/legendtier/census.tsv.

THE RULE (docs/EVALS.md, BAND K (tiers)). An entry is in schema KEY's pack when at least ONE THIRD of that schema's
measured answers carried it. Holding a line costs it once and saves it on every later answer that carries it, so an
entry pays for itself the second time it is met — one third is that rule applied to "I will call this verb three
times". The core tier's lines are not in the census at all (census.py leaves them out).

Membership is a cost decision and never a correctness one: an entry in no tier the caller holds stays in the answer
that carries it. That is the only reason a census taken on corpora outside this repository may decide it.

    python3 bench/legendtier/packs_build.py            rewrites src/legendpacks.h
    python3 bench/legendtier/packs_build.py --check    rewrites nothing; exit 1 if the header differs (the gate runs this)
"""
import pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
CENSUS = ROOT / "bench" / "legendtier" / "census.tsv"
HEADER = ROOT / "src" / "legendpacks.h"

def build():
    answers, rows = {}, []
    for raw in CENSUS.read_text(encoding="utf-8").splitlines():
        if not raw or raw.startswith("#"):
            continue
        f = raw.split("\t")
        if f[0] == "N" and len(f) == 3:
            answers[f[1]] = int(f[2])
        elif f[0] == "E" and len(f) == 6:
            rows.append((f[1], int(f[2]), f[3], f[4], f[5]))
        else:
            sys.exit("packs_build: unreadable census row: %r" % raw)
    kept = sorted((key, attr, tag, item) for key, n, attr, tag, item in rows if answers.get(key, 0) > 0 and 3 * n >= answers[key])
    for field in [x for row in kept for x in row] + list(answers):
        if '"' in field or "\\" in field:
            sys.exit("packs_build: a census field needs escaping, which this generator does not do: %r" % field)
    q = lambda s: '"%s"' % s
    out = [
        "#pragma once",
        "// legendpacks.h — GENERATED by bench/legendtier/packs_build.py from bench/legendtier/census.tsv. Do not edit by hand:",
        "// test/legendtiercheck.sh (P0) regenerates it and fails on any difference.",
        "//",
        "// A pack is the legend-dictionary entries at least ONE THIRD of a schema's measured answers carried. A row names an",
        "// entry by what it defines — attribute, element, listed item — so rewording a definition does not drop it from its",
        "// pack. `@purpose` is the schema's own line, `@file-scope` the module-scope name reading. legenddict.h packTier",
        "// resolves the rows; a schema absent from kLegendPackCensus was never measured and has no pack.",
        "#include <cstddef>",
        "#include <string_view>",
        "",
        "namespace rw::legenddict",
        "{",
        "",
        "struct LegendPackCensus",
        "{",
        "    std::string_view key;",
        "    std::size_t      answers;   // how many answers of this schema the census measured",
        "};",
        "",
        "struct LegendPackRow",
        "{",
        "    std::string_view key;",
        "    std::string_view attr;",
        "    std::string_view onTag;",
        "    std::string_view valueItem;",
        "};",
        "",
        "// %d schemas measured, %d answers." % (len(answers), sum(answers.values())),
        "inline constexpr LegendPackCensus kLegendPackCensus[] =",
        "{",
    ]
    out += ["    { %s, %d }," % (q(k), answers[k]) for k in sorted(answers)]
    out += ["};", "", "// %d rows." % len(kept), "inline constexpr LegendPackRow kLegendPackRows[] =", "{"]
    out += ["    { %s, %s, %s, %s }," % tuple(q(x) for x in row) for row in kept]
    out += ["};", "", "} // namespace rw::legenddict", ""]
    return "\n".join(out)

def main():
    text = build()
    if "--check" in sys.argv[1:]:
        if not HEADER.exists() or HEADER.read_text(encoding="utf-8") != text:
            print("packs_build: src/legendpacks.h is not what bench/legendtier/census.tsv produces — run python3 bench/legendtier/packs_build.py")
            sys.exit(1)
        print("packs_build: src/legendpacks.h is current")
        return
    HEADER.write_text(text, encoding="utf-8")
    print("packs_build: wrote %s" % HEADER.relative_to(ROOT))

if __name__ == "__main__":
    main()
